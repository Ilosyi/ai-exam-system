// ============================================================================
// main.go - 程序入口文件
// ============================================================================
//
// 这是整个后端服务的入口点。Go 语言要求每个可执行程序都必须有一个 main 包，
// 且该包中必须包含一个 main() 函数。
//
// 本项目的 main.go 非常简洁，只负责一件事：调用 bootstrap.Start() 启动应用。
// 这种设计将"启动逻辑"与"程序入口"分离，使得启动流程可以在测试中被复用。
//
// 学习要点：
// 1. Go 程序的入口约定：package main + func main()
// 2. 错误处理：if err := ...; err != nil 是 Go 的惯用模式
// 3. log.Fatal：打印错误后调用 os.Exit(1)，终止程序
// ============================================================================

package main

import (
	"log" // Go 标准库的日志包，提供基本的日志输出功能

	// 导入我们自己的 bootstrap 包，它负责整个应用的初始化和启动
	"week05/homework/server/bootstrap"
)

// main 是程序的入口函数。
// 它调用 bootstrap.Start("") 来启动 HTTP 服务器。
// 传入空字符串 "" 表示使用配置文件中的默认端口（通常是 8080）。
// 如果启动过程中发生任何错误（如端口被占用、配置文件缺失），程序会打印错误并退出。
func main() {
	// bootstrap.Start 内部会完成以下工作：
	// 1. 解析项目根目录
	// 2. 加载配置文件 (config.json)
	// 3. 初始化 SQLite 数据库连接
	// 4. 执行数据库迁移（创建/更新表结构）
	// 5. 创建所有依赖（Repository、Service、Handler）
	// 6. 注册所有 HTTP 路由
	// 7. 启动 HTTP 服务器监听指定端口
	if err := bootstrap.Start(""); err != nil {
		// log.Fatal 会先打印错误信息，然后调用 os.Exit(1) 终止进程
		log.Fatal(err)
	}
}
